"""Writes port/renderer/textures/switch_glyph_art.inc: the Switch button pictures of the game's text, from "Switch Button Icons and Controls"
by Zacksly (CC BY 3.0: https://creativecommons.org/licenses/by/3.0/, https://zacksly.itch.io; see THIRD_PARTY_NOTICES.md).

    python tools/make_switch_glyphs.py "PATH/Switch 2 Button Icons and Controls" [--theme "Buttons Full Solid/White"]

The pack's pictures are cut to their shapes and scaled into the 24 x 16 cells the game's font sheet holds (alpha-weighted, so no dark
fringe), and written as RGBA bytes. This is a change to the originals, as the license asks to be said (THIRD_PARTY_NOTICES.md says it).
"""
import argparse
import pathlib

from PIL import Image

# The font sheet's button cells in the game's order (renderer/textures/button_glyphs.cpp), the pack's picture for each, and the box inside the
# 24 x 16 cell that the game's own picture fills (measured on a dumped sheet): the round buttons 16 x 16 from x 2, the shoulder and trigger
# pills 21 x 13 from (3, 2), the two stick cells 14 x 13 from (1, 2).
DISC = (2, 0, 18, 16)
PILL = (3, 2, 24, 15)
STICK = (1, 2, 15, 15)
CELLS = [
    ("Cross", "B", DISC),
    ("Square", "Y", DISC),
    ("Triangle", "X", DISC),
    ("Circle", "A", DISC),
    ("L1", "L", PILL),
    ("L2", "ZL", PILL),
    ("R1", "R", PILL),
    ("R2", "ZR", PILL),
    ("RightStick", "Right Stick Click", STICK),
    ("LeftStick", "Left Stick Click", STICK),
]
CW, CH = 24, 16


def premultiplied(image):
    out = Image.new("RGBA", image.size)
    src, dst = image.load(), out.load()
    for y in range(image.height):
        for x in range(image.width):
            r, g, b, a = src[x, y]
            dst[x, y] = (r * a // 255, g * a // 255, b * a // 255, a)
    return out


def straight(image):
    out = Image.new("RGBA", image.size)
    src, dst = image.load(), out.load()
    for y in range(image.height):
        for x in range(image.width):
            r, g, b, a = src[x, y]
            dst[x, y] = (0, 0, 0, 0) if a == 0 else (min(255, r * 255 // a), min(255, g * 255 // a), min(255, b * 255 // a), a)
    return out


def cell_picture(path, box):
    icon = Image.open(path).convert("RGBA")
    icon = icon.crop(icon.split()[3].point(lambda v: 255 if v > 40 else 0).getbbox())
    bw, bh = box[2] - box[0], box[3] - box[1]
    scale = min(bw / icon.width, bh / icon.height)
    size = (max(1, round(icon.width * scale)), max(1, round(icon.height * scale)))
    small = straight(premultiplied(icon).resize(size, Image.LANCZOS))
    canvas = Image.new("RGBA", (CW, CH), (0, 0, 0, 0))
    canvas.alpha_composite(small, (box[0] + (bw - size[0]) // 2, box[1] + (bh - size[1]) // 2))
    return canvas


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("pack")
    ap.add_argument("--theme", default="Buttons Full Solid/White")
    args = ap.parse_args()
    root = pathlib.Path(args.pack)
    if not (root / args.theme).is_dir():
        inner = next((p for p in root.iterdir() if p.is_dir() and (p / args.theme).is_dir()), None)
        if inner is None:
            raise SystemExit("no folder %r in %s" % (args.theme, root))
        root = inner
    folder = root / args.theme / "256w"
    lines = [
        "// Generated by tools/make_switch_glyphs.py from the Switch Button Icons and Controls by Zacksly, CC BY 3.0",
        "// (https://creativecommons.org/licenses/by/3.0/, https://zacksly.itch.io), scaled into the game's 24 x 16 button cells: see THIRD_PARTY_NOTICES.md. Do not edit.",
        "// One picture per button cell of the font sheet (Cross, Square, Triangle, Circle, L1, L2, R1, R2, right stick, left stick); RGBA bytes, row by row, alpha 0 to 255.",
        "{",
    ]
    for name, icon, box in CELLS:
        picture = cell_picture(folder / (icon + ".png"), box)
        lines.append("    // %s (%s)" % (name, icon))
        lines.append("    {")
        for y in range(CH):
            row = ", ".join("%d, %d, %d, %d" % picture.getpixel((x, y)) for x in range(CW))
            lines.append("        " + row + ",")
        lines.append("    },")
    lines.append("}")
    out = pathlib.Path(__file__).resolve().parent.parent / "port/renderer/textures/switch_glyph_art.inc"
    out.write_text(chr(10).join(lines) + chr(10), encoding="utf8", newline=chr(10))
    print(out, out.stat().st_size, "bytes")


main()
